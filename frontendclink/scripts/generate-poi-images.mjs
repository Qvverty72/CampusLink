import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDirectory = resolve(root, 'assets/images/poimages');
const outputPath = resolve(root, 'src/three/assets/poiImages.generated.ts');

// Metro requires literal paths. Density variants belong to their base asset.
const entries = await readdir(imagesDirectory, { withFileTypes: true });
const files = entries
  .filter(entry => entry.isFile() && /\.(png|jpe?g|webp)$/i.test(entry.name)
    && !/@\d+(?:\.\d+)?x\.[^.]+$/i.test(entry.name))
  .map(entry => entry.name)
  .sort();

const content = [
  '// Generated by npm run poi:images. Add photos in assets/images/poimages, not here.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export const POI_IMAGES: Readonly<Record<string, ImageSourcePropType>> = {',
  ...files.map(name => `  [${JSON.stringify(name)}]: require(${JSON.stringify(`../../../assets/images/poimages/${name}`)}),`),
  '};',
  '',
].join('\n');

let previous;
try {
  previous = await readFile(outputPath, 'utf8');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
if (previous?.replace(/\r\n/g, '\n') !== content) {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content, 'utf8');
}
console.log(`POI images: ${files.length} registered.`);
